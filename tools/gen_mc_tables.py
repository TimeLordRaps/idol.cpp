"""Generate src/mc_tables.h from scikit-image's classic marching-cubes tables.

The triangle table (CASESCLASSIC) and the edge endpoint offsets are data taken from skimage.measure's Lewiner module,
which is BSD-3-Clause licensed. Regenerate with scikit-image installed:

    python tools/gen_mc_tables.py
"""
import os

import numpy as np
from skimage.measure import _marching_cubes_lewiner as lewiner
from skimage.measure import _marching_cubes_lewiner_luts as luts

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "src", "mc_tables.h")


def rows(values):
    return "{\n" + ",\n".join("    {" + ", ".join(str(int(v)) for v in row) + "}" for row in values) + "\n}"


def main():
    cases = lewiner._to_array(luts.CASESCLASSIC)
    assert cases.shape == (256, 16), cases.shape
    ex = np.asarray(lewiner.EDGETORELATIVEPOSX)
    ey = np.asarray(lewiner.EDGETORELATIVEPOSY)
    ez = np.asarray(lewiner.EDGETORELATIVEPOSZ)
    assert ex.shape == ey.shape == ez.shape == (12, 2)

    lines = [
        "// Generated by tools/gen_mc_tables.py from scikit-image's classic marching-cubes tables. Do not edit by hand.",
        "// Data only; scikit-image is BSD-3-Clause licensed. See docs/notice.html.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace idol::detail {",
        "",
        "// Triangles per cube case: edge indices, three per triangle, -1 ends the list.",
        "inline constexpr std::int8_t kCases[256][16] = " + rows(cases) + ";",
        "",
        "// Endpoints of each cube edge as offsets (0 or 1) along x, y and z.",
        "inline constexpr std::int8_t kEdgeOffsets[12][2][3] = {",
    ]
    for e in range(12):
        lines.append("    {{%d, %d, %d}, {%d, %d, %d}}," % (ex[e, 0], ey[e, 0], ez[e, 0], ex[e, 1], ey[e, 1], ez[e, 1]))
    lines += ["};", "", "}  // namespace idol::detail", ""]

    with open(OUT, "w", encoding="ascii", newline="\n") as stream:
        stream.write("\n".join(lines))
    print(f"wrote {os.path.normpath(OUT)} ({int((cases != -1).sum()) // 3} triangle entries)")


if __name__ == "__main__":
    main()
